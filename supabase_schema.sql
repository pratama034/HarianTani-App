-- 1. TABEL: lahan
CREATE TABLE IF NOT EXISTS public.lahan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  luas TEXT NOT NULL,
  tanaman TEXT NOT NULL,
  tanggal_tanam DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL: jadwal_perawatan
CREATE TABLE IF NOT EXISTS public.jadwal_perawatan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lahan TEXT NOT NULL,
  tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
  waktu TEXT NOT NULL,
  kegiatan TEXT NOT NULL,
  selesai BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL: jurnal_lapangan
CREATE TABLE IF NOT EXISTS public.jurnal_lapangan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lahan TEXT NOT NULL,
  tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
  catatan TEXT NOT NULL,
  biaya NUMERIC NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABEL: laporan_panen
CREATE TABLE IF NOT EXISTS public.laporan_panen (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_lahan TEXT NOT NULL,
  tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
  jumlah NUMERIC NOT NULL DEFAULT 0,
  satuan TEXT NOT NULL DEFAULT 'Kg',
  harga_jual NUMERIC NOT NULL DEFAULT 0,
  selesai BOOLEAN NOT NULL DEFAULT FALSE,
  commodity TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================================
-- KONFIGURASI ROW LEVEL SECURITY (RLS) & HAK AKSES API
-- Mengizinkan anon key untuk operasi SELECT, INSERT, UPDATE, DELETE (Pekan 4)
-- ============================================================================

ALTER TABLE public.lahan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jadwal_perawatan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.jurnal_lapangan ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.laporan_panen ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Akses Publik Lahan" ON public.lahan;
CREATE POLICY "Akses Publik Lahan" ON public.lahan
  FOR ALL TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Akses Publik Jadwal" ON public.jadwal_perawatan;
CREATE POLICY "Akses Publik Jadwal" ON public.jadwal_perawatan
  FOR ALL TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Akses Publik Jurnal" ON public.jurnal_lapangan;
CREATE POLICY "Akses Publik Jurnal" ON public.jurnal_lapangan
  FOR ALL TO anon, authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Akses Publik Panen" ON public.laporan_panen;
CREATE POLICY "Akses Publik Panen" ON public.laporan_panen
  FOR ALL TO anon, authenticated
  USING (true)
  WITH CHECK (true);

